/**
 * Per-OS remote commands for the browserpaw plugin. Each platform turns intent (inspect, set up, find,
 * launch, stop a profile) into one script for the SSH host, plus the command line that runs it, and the
 * plugin parses the output the same way everywhere:
 *   inspect/setup → `key=value` lines;   status → see parseStatus.
 *
 * linux, macos: POSIX sh (`sh -c '…'`, whatever the login shell). Chromium on both reads native messaging
 *   manifests from <user-data-dir>/NativeMessagingHosts, so each profile gets its own, pointing at a wrapper
 *   that sets the BrowserPaw tool profile.
 * windows: PowerShell via -EncodedCommand (works when the OpenSSH default shell is cmd or PowerShell).
 *   Native messaging hosts are registered per user in HKCU, shared by every profile, so the tool profile
 *   travels in Chromium's environment instead (the native host inherits it). Chromium is started by a
 *   per-profile scheduled task so it runs on the user's desktop and outlives the SSH session (Windows
 *   OpenSSH kills a session's processes when it ends).
 */
import { createHash } from 'node:crypto';

export type Os = 'linux' | 'macos' | 'windows';
export type Browser = 'chromium' | 'chrome' | 'edge';
export const HOST_NAME = 'com.chromemcp.nativehost';

/** Absolute paths as resolved on the host by `inspect`. */
export interface Resolved { dir: string; ext: string; extensionId: string; nativeHost: string; chromium: string }
export interface LaunchOpts { browser: Browser; toolProfile: string; headless: boolean; extraArgs: string; env: [string, string][]; task: string; proxy?: string; proxyBypass?: string }

export interface Platform {
  os: Os;
  defaults(browser: Browser): { profilesDir: string; chromium: string; env: string };
  /** BrowserPaw's native host launcher, relative to the checkout. */
  nativeHostRel: string;
  /** Command line that runs `script` on the host. */
  wrap(script: string): string;
  /** Prints ext=, manifest= (base64), nativehost=, chromium=, and dir= (creating the profile dir) when `profile` is given. */
  inspect(x: { ext: string; nativeHost: string; chromium: string; profile?: string }): string;
  /** Writes the native messaging manifest (and wrapper/registry). Prints done=1 (and previous= on Windows). */
  setup(r: Resolved, profile: string, browser: Browser, toolProfile: string): string;
  /** Output for parseStatus. */
  status(profileDir: string): string;
  /** Starts Chromium detached. Prints launched=1. */
  launch(r: Resolved, o: LaunchOpts): string;
  stop(pid: number): string;
  /** Chrome's id for an unpacked extension (manifest `key`, else a hash of the path as Chrome sees it). */
  extensionId(absPath: string, manifestKey?: string): string;
}

const idFrom = (bytes: Buffer) => [...createHash('sha256').update(bytes).digest('hex').slice(0, 32)].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('');

// ---------------------------------------------------------------- POSIX (linux, macos)

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
/** Shell word for a path; a leading `~/` becomes "$HOME"/… so it expands remotely. */
export const sp = (p: string) => (p === '~' ? '"$HOME"' : p.startsWith('~/') ? `"$HOME"/${sq(p.slice(2))}` : sq(p));

function posix(os: 'linux' | 'macos'): Platform {
  const mac = os === 'macos';
  return {
    os,
    defaults: (b) => ({
      profilesDir: mac ? '~/Library/Application Support/mcontrolprogram-browserpaw' : '~/.local/share/mcontrolprogram-browserpaw',
      chromium: mac
        ? { chromium: '/Applications/Chromium.app/Contents/MacOS/Chromium', chrome: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', edge: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge' }[b]
        : { chromium: 'chromium', chrome: 'google-chrome', edge: 'microsoft-edge' }[b],
      env: mac ? '' : 'DISPLAY=:0',
    }),
    nativeHostRel: 'app/native-server/dist/run_host.sh',
    wrap: (script) => `sh -c ${sq(script)}`,
    // ponytail: only POSIX sh + coreutils common to GNU and BSD (no realpath -e, base64 -w0, setsid on mac)
    inspect: (x) => [
      `if ext=$(cd ${sp(x.ext)} 2>/dev/null && pwd -P); then echo "ext=$ext"; echo "manifest=$(base64 < "$ext/manifest.json" 2>/dev/null | tr -d '\\n')"; fi`,
      `nh=${sp(x.nativeHost)}; [ -f "$nh" ] && echo "nativehost=$(cd "$(dirname "$nh")" && pwd -P)/$(basename "$nh")"`,
      `echo "chromium=$(command -v ${sp(x.chromium)} 2>/dev/null)"`,
      x.profile ? `mkdir -p ${sp(x.profile)} && echo "dir=$(cd ${sp(x.profile)} && pwd -P)"` : '',
      'true',
    ].filter(Boolean).join('; '),
    setup(r, profile, _browser, toolProfile) {
      const wrapper = `#!/bin/sh\n# Generated by MControlProgram (browserpaw plugin) for profile ${profile}; overwritten on setup.\nexport CHROME_MCP_TOOL_PROFILE=${sq(toolProfile)}\nexec ${sq(r.nativeHost)} "$@"\n`;
      const manifest = JSON.stringify({ name: HOST_NAME, description: `BrowserPaw (MControlProgram profile ${profile})`, path: `${r.dir}/browserpaw-host.sh`, type: 'stdio', allowed_origins: [`chrome-extension://${r.extensionId}/`] }, null, 2);
      const put = (content: string, file: string, mode: string) => `printf %s ${sq(content)} > ${sq(file)} && chmod ${mode} ${sq(file)}`;
      return [`mkdir -p ${sq(`${r.dir}/NativeMessagingHosts`)}`, put(wrapper, `${r.dir}/browserpaw-host.sh`, '700'), put(manifest, `${r.dir}/NativeMessagingHosts/${HOST_NAME}.json`, '600'), 'echo done=1'].join(' && ');
    },
    // markers are written split (@@S''S@@) so `ps` listing our own shell cannot fake them.
    // ss and lsof live in /usr/sbin or /sbin, which launchd/ssh PATHs often lack; without them no bridge is ever found.
    status: (d) => `PATH="$PATH:/usr/sbin:/sbin"; [ -d ${sp(d)} ] && echo "dir=$(cd ${sp(d)} && pwd -P)"; ps -eo pid=,ppid=,args=; echo @@S''S@@; ss -ltnpH 2>/dev/null || lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null; echo @@TOK''EN@@; cat "$HOME"/.chrome-mcp/bridge-token 2>/dev/null; true`,
    launch(r, o) {
      const env = o.env.map(([k, v]) => `export ${k}=${sq(v)};`).join(' ');
      const args = [`--user-data-dir=${sq(r.dir)}`, `--load-extension=${sq(r.ext)}`, ...commonArgs(o).map(sq), o.extraArgs].filter(Boolean).join(' ');
      const log = sq(`${r.dir}/chromium.log`);
      const app = /^(.*\.app)\/Contents\/MacOS\//.exec(r.chromium)?.[1];
      // macOS: LaunchServices puts the window on the logged-in user's desktop and detaches it from SSH
      const start = mac && app ? `open -n -a ${sq(app)} --args ${args} about:blank`
        : `if command -v setsid >/dev/null 2>&1; then setsid -f ${sq(r.chromium)} ${args} about:blank >> ${log} 2>&1 < /dev/null; else nohup ${sq(r.chromium)} ${args} about:blank >> ${log} 2>&1 < /dev/null & fi`;
      // ponytail: extraArgs is appended verbatim (shell syntax); it is admin-only config like the ssh host itself
      return `${env} cd ${sq(r.dir)} && ${start}; echo launched=1`;
    },
    stop: (pid) => `kill ${pid}`,
    extensionId: (p, key) => idFrom(key ? Buffer.from(key, 'base64') : Buffer.from(p)),
  };
}

// ---------------------------------------------------------------- Windows (PowerShell)

const pq = (s: string) => `'${s.replace(/'/g, "''")}'`;
/** PowerShell expression for a path; `~/…` or `~\…` is joined onto $HOME, `/` becomes `\`. */
export const pp = (p: string) => {
  const w = p.replace(/\//g, '\\');
  return w === '~' ? '$HOME' : w.startsWith('~\\') ? `(Join-Path $HOME ${pq(w.slice(2))})` : pq(w);
};
/** Quote one argument for a Windows command line (CommandLineToArgvW rules). */
const wq = (s: string) => (/[\s"]/.test(s) || s === '' ? `"${s.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\+)$/, '$1$1')}"` : s);
const PS_PRELUDE = "$ErrorActionPreference='SilentlyContinue';$ProgressPreference='SilentlyContinue';[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false);";
const REG = { chromium: 'Chromium', chrome: 'Google\\Chrome', edge: 'Microsoft\\Edge' } as const;

const windows: Platform = {
  os: 'windows',
  defaults: (b) => ({
    profilesDir: '~/AppData/Local/mcontrolprogram-browserpaw',
    chromium: { chromium: '~/AppData/Local/Chromium/Application/chrome.exe', chrome: 'C:/Program Files/Google/Chrome/Application/chrome.exe', edge: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' }[b],
    env: '',
  }),
  nativeHostRel: 'app/native-server/dist/run_host.bat',
  wrap: (script) => `powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand ${Buffer.from(PS_PRELUDE + script, 'utf16le').toString('base64')}`,
  inspect: (x) => [
    'function R($p){if(Test-Path -LiteralPath $p){(Resolve-Path -LiteralPath $p).ProviderPath}}',
    `$e=R ${pp(x.ext)};if($e){"ext=$e";"manifest="+[Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $e 'manifest.json')))}`,
    `"nativehost="+(R ${pp(x.nativeHost)})`,
    `$c=${pp(x.chromium)};"chromium="+$(if(Test-Path -LiteralPath $c -PathType Leaf){R $c}else{(Get-Command $c -CommandType Application|Select-Object -First 1).Source})`,
    x.profile ? `"dir="+(New-Item -ItemType Directory -Force -Path ${pp(x.profile)}).FullName` : '',
  ].filter(Boolean).join(';'),
  setup(r, _profile, browser) {
    // One registration per user and browser, shared by all profiles: merge origins with what is there.
    const key = `HKCU:\\Software\\${REG[browser]}\\NativeMessagingHosts\\${HOST_NAME}`;
    return [
      `$k=${pq(key)};$old=(Get-Item -LiteralPath $k).GetValue('');"previous=$old"`,
      `$o=@(${pq(`chrome-extension://${r.extensionId}/`)});if($old -and (Test-Path -LiteralPath $old)){$o+=@((Get-Content -Raw -LiteralPath $old|ConvertFrom-Json).allowed_origins)}`,
      `$m=Join-Path (Split-Path ${pq(r.dir)}) ${pq(`${HOST_NAME}.json`)}`,
      `$j=[ordered]@{name=${pq(HOST_NAME)};description='BrowserPaw (MControlProgram)';path=${pq(r.nativeHost)};type='stdio';allowed_origins=@($o|Where-Object{$_}|Select-Object -Unique)}|ConvertTo-Json`,
      '[IO.File]::WriteAllText($m,$j)', // UTF-8 without BOM
      'New-Item -Path $k -Force|Out-Null;Set-Item -LiteralPath $k -Value $m',
      `if((Get-Item -LiteralPath $k).GetValue('') -eq $m){'done=1'}`,
    ].join(';');
  },
  status: (d) => [
    `$d=${pp(d)};if(Test-Path -LiteralPath $d){"dir="+(Resolve-Path -LiteralPath $d).ProviderPath}`,
    'Get-CimInstance Win32_Process|ForEach-Object{"$($_.ProcessId) $($_.ParentProcessId) $($_.CommandLine)"}',
    "'@@S'+'S@@'",
    'Get-NetTCPConnection -State Listen -LocalAddress 127.0.0.1|ForEach-Object{"LISTEN 127.0.0.1:$($_.LocalPort) pid=$($_.OwningProcess)"}',
    "'@@TOK'+'EN@@'",
    "Get-Content -Raw (Join-Path $HOME '.chrome-mcp\\bridge-token')",
  ].join(';'),
  launch(r, o) {
    const env = [['CHROME_MCP_TOOL_PROFILE', o.toolProfile] as [string, string], ...o.env].map(([k, v]) => `set "${k}=${v}"&& `).join('');
    const args = [`--user-data-dir=${wq(r.dir)}`, `--load-extension=${wq(r.ext)}`, ...commonArgs(o).map(wq), o.extraArgs, 'about:blank'].filter(Boolean).join(' ');
    // cmd /c: env for Chromium (and so the native host); `start ""` lets the task finish while Chromium runs
    const cmdline = `/c ${env}start "" ${wq(r.chromium)} ${args}`;
    return [
      `$a=New-ScheduledTaskAction -Execute 'cmd.exe' -Argument ${pq(cmdline)} -WorkingDirectory ${pq(r.dir)}`,
      '$p=New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\\$env:USERNAME" -LogonType Interactive',
      '$s=New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries',
      `Register-ScheduledTask -TaskName ${pq(o.task)} -Action $a -Principal $p -Settings $s -Force|Out-Null`,
      `Start-ScheduledTask -TaskName ${pq(o.task)};'launched=1'`,
    ].join(';');
  },
  stop: (pid) => `Stop-Process -Id ${pid}`,
  // Chrome hashes the path as UTF-16LE with the drive letter upper-cased (crx_file::id_util)
  extensionId: (p, key) => idFrom(key ? Buffer.from(key, 'base64') : Buffer.from(p.replace(/^([a-z]):/, (_, d: string) => `${d.toUpperCase()}:`), 'utf16le')),
};

function commonArgs(o: LaunchOpts) {
  return [
    '--no-first-run', '--no-default-browser-check',
    // branded Chrome/Edge 137+ ignore --load-extension unless this feature is disabled
    ...(o.browser !== 'chromium' ? ['--disable-features=DisableLoadExtensionCommandLineSwitch'] : []),
    ...(o.headless ? ['--headless=new'] : []),
    ...(o.proxy ? [`--proxy-server=${o.proxy}`] : []),
    ...(o.proxy && o.proxyBypass ? [`--proxy-bypass-list=${o.proxyBypass}`] : []),
  ];
}

export const platforms: Record<Os, Platform> = { linux: posix('linux'), macos: posix('macos'), windows };

/** Probe commands for OS auto-detection: `uname -s` works on linux/macos; the PowerShell probe on Windows. */
export const PROBE_UNIX = 'uname -s';
export const PROBE_WINDOWS = windows.wrap("'windows'");
export const osFromUname = (s: string): Os | undefined => (/^Linux/m.test(s) ? 'linux' : /^Darwin/m.test(s) ? 'macos' : undefined);

// ---------------------------------------------------------------- shared parsing

export const kv = (out: string) => Object.fromEntries(out.split('\n').map((l) => /^([a-z]+)=(.*)$/.exec(l)).filter((m): m is RegExpExecArray => !!m).map((m) => [m[1]!, m[2]!]));

export interface Status { dir?: string; chromiumPid?: number; bridge?: { pid: number; port: number; token: string } }

/**
 * Find the profile's Chromium and the BrowserPaw bridge it started. The bridge's port comes from the
 * listening sockets (ss, lsof or Get-NetTCPConnection); the process tree ties it to this profile.
 * BrowserPaw's own registry is keyed by extension id, which every profile shares, so it cannot tell
 * profiles apart. The bearer token is per user, shared by all bridges.
 */
export function parseStatus(out: string): Status {
  const [psOut = '', rest = ''] = out.split('\n@@SS@@\n');
  const [sockOut = '', token = ''] = rest.split('\n@@TOKEN@@\n').map((x) => x.trim());
  const dir = kv(psOut).dir || undefined;
  const procs = new Map<number, { ppid: number; args: string }>();
  for (const l of psOut.split('\n')) { const m = /^\s*(\d+)\s+(\d+)\s+(.*)$/.exec(l); if (m) procs.set(Number(m[1]), { ppid: Number(m[2]), args: m[3]! }); }
  if (!dir) return {};
  const flag = `--user-data-dir=${dir}`;
  // quotes are dropped so Windows command lines (--user-data-dir="C:\…") match too
  const chromiumPid = [...procs].find(([, x]) => { const a = x.args.replace(/"/g, ''); return !a.includes(' --type=') && (a.includes(`${flag} `) || a.endsWith(flag)); })?.[0];
  if (!chromiumPid) return { dir };
  const descends = (pid: number) => { for (let i = 0; i < 20 && pid > 0; i++) { if (pid === chromiumPid) return true; pid = procs.get(pid)?.ppid ?? 0; } return false; };
  if (!/^[0-9a-fA-F]{48,64}$/.test(token)) return { dir, chromiumPid };
  for (const l of sockOut.split('\n')) {
    // ss / our Windows lines: "… 127.0.0.1:PORT … pid=PID"; lsof: "COMMAND PID USER … TCP 127.0.0.1:PORT (LISTEN)"
    const m = /\s127\.0\.0\.1:(\d+)\s.*\bpid=(\d+)/.exec(l) ?? ((x) => x && [x[0], x[2], x[1]])(/^\S+\s+(\d+)\s.*\s127\.0\.0\.1:(\d+)\s+\(LISTEN\)/.exec(l));
    // only the bridge's port range: the bridge's own children (e.g. the Jev decider on 8009) also descend from chromium
    if (m && Number(m[1]) >= 12306 && Number(m[1]) <= 12316 && descends(Number(m[2]))) return { dir, chromiumPid, bridge: { pid: Number(m[2]), port: Number(m[1]), token } };
  }
  return { dir, chromiumPid };
}
